"""Convert every rule to deployable SIEM queries with pySigma and write docs/queries.md.

Targets per log source:
  Windows process_creation -> Splunk (Windows pipeline) + Microsoft Defender XDR KQL
  Windows Security log     -> Splunk (Windows pipeline) + Microsoft Sentinel KQL (SecurityEvent)
  Windows System log       -> Splunk (Windows pipeline)
  AWS / M365               -> Splunk (field names as in the raw log)

A rule that fails to convert fails CI, so a broken rule can't ship.

Usage:
    python -m dac.convert           # regenerate docs/queries.md
    python -m dac.convert --check   # exit 1 if docs/queries.md is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sigma.backends.kusto import KustoBackend
from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.pipelines.azuremonitor import azure_monitor_pipeline
from sigma.pipelines.microsoftxdr import microsoft_xdr_pipeline
from sigma.pipelines.splunk import splunk_windows_pipeline

ROOT = Path(__file__).resolve().parent.parent
RULES, OUT = ROOT / "rules", ROOT / "docs" / "queries.md"


def targets_for(logsource: dict) -> list[tuple[str, str, object]]:
    """Return (label, code-fence language, backend factory) for a rule's log source."""
    product, category, service = logsource.get("product"), logsource.get("category"), logsource.get("service")
    if product == "windows":
        out = [("Splunk", "spl", lambda: SplunkBackend(splunk_windows_pipeline()))]
        if category == "process_creation":
            out.append(("Microsoft Defender XDR (KQL)", "kql", lambda: KustoBackend(microsoft_xdr_pipeline())))
        elif service == "security":
            out.append(("Microsoft Sentinel (KQL)", "kql",
                        lambda: KustoBackend(azure_monitor_pipeline(query_table="SecurityEvent"))))
        return out
    return [("Splunk", "spl", lambda: SplunkBackend())]


def convert_rule(path: Path) -> list[tuple[str, str, str]]:
    text = path.read_text(encoding="utf-8")
    rule = SigmaCollection.from_yaml(text).rules[0]
    logsource = {"product": rule.logsource.product, "category": rule.logsource.category,
                 "service": rule.logsource.service}
    results = []
    for label, lang, factory in targets_for(logsource):
        # Pipelines rewrite field names in place, so every backend gets a freshly parsed rule
        query = factory().convert(SigmaCollection.from_yaml(text))[0]
        results.append((label, lang, query))
    return results


def render() -> str:
    lines = ["# Converted queries", "",
             "Generated by `python -m dac.convert` with pySigma. Do not edit by hand.", ""]
    for path in sorted(RULES.rglob("*.yml")):
        title = SigmaCollection.from_yaml(path.read_text(encoding="utf-8")).rules[0].title
        rel = path.relative_to(ROOT).as_posix()
        lines += [f"## {title}", "", f"Source: [`{rel}`](../{rel})", ""]
        for label, lang, query in convert_rule(path):
            lines += [f"**{label}**", "", f"```{lang}", query, "```", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/queries.md is stale; run: python -m dac.convert", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
