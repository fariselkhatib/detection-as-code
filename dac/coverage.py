"""Generate docs/coverage.md: which ATT&CK tactics and techniques the rule set covers.

Usage:
    python -m dac.coverage           # regenerate
    python -m dac.coverage --check   # exit 1 if stale
"""
from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from .engine import load_rules
from .validate import TACTICS, TECHNIQUE_TAG

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "coverage.md"
TACTIC_ORDER = ["reconnaissance", "resource-development", "initial-access", "execution", "persistence",
                "privilege-escalation", "defense-evasion", "credential-access", "discovery",
                "lateral-movement", "collection", "command-and-control", "exfiltration", "impact"]


def render() -> str:
    rules = load_rules(ROOT / "rules")
    by_tactic = defaultdict(list)
    techniques = set()
    for rule in rules:
        # Tags are written as tactic, then that tactic's techniques (Sigma convention),
        # so a technique belongs to the most recent tactic tag above it.
        current = None
        for t in rule.raw["tags"]:
            name = t.split(".", 1)[1]
            if name in TACTICS:
                current = name
                by_tactic[current].append((rule, []))
            elif TECHNIQUE_TAG.match(t) and current:
                by_tactic[current][-1][1].append(name.upper())
                techniques.add(name.upper())

    lines = ["# ATT&CK coverage", "",
             f"{len(rules)} rules, {len(techniques)} techniques, "
             f"{len(by_tactic)} of {len(TACTIC_ORDER)} tactics. Generated by `python -m dac.coverage`.", "",
             "| Tactic | Rules | Techniques |", "|---|---|---|"]
    for tactic in TACTIC_ORDER:
        entries = by_tactic.get(tactic, [])
        techs = sorted({t for _, ts in entries for t in ts})
        mark = len(entries) if entries else "-"
        links = ", ".join(f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)" for t in techs)
        lines.append(f"| {tactic} | {mark} | {links} |")

    lines += ["", "## Rules", "", "| Rule | Level | Log source | Techniques |", "|---|---|---|---|"]
    for rule in sorted(rules, key=lambda r: r.title):
        ls = rule.raw["logsource"]
        src = "/".join(str(ls[k]) for k in ("product", "category", "service") if ls.get(k))
        techs = ", ".join(t.split(".", 1)[1].upper() for t in rule.raw["tags"] if TECHNIQUE_TAG.match(t))
        rel = rule.path.relative_to(ROOT).as_posix()
        lines.append(f"| [{rule.title}](../{rel}) | {rule.raw['level']} | {src} | {techs} |")
    lines += ["", "## Gaps worth closing next", "",
              "Tactics with no coverage above are the obvious backlog. Persistence (scheduled tasks, "
              "Run keys, new services outside PsExec) and command-and-control (beaconing, tunneling tools) "
              "are the highest-value additions for a ransomware-focused rule set.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/coverage.md is stale; run: python -m dac.coverage", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
